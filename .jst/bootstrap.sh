#!/usr/bin/env bash
# .jst/bootstrap.sh — the optional per-worktree bootstrap hook for
# jira-sdlc-tools. jira-task-executor runs it automatically in its step 1,
# once per worktree, at the moment someone is about to work in it. Windows
# twin: bootstrap.ps1 (identical behaviour, output and exit codes).
#
# This project is a stateless Vite + React frontend: no database, no
# containers, nothing external to duplicate per worktree. So the hook only
# installs dependencies, copies the gitignored local files a fresh worktree
# lacks (see step 2), and hands each worktree its own non-colliding dev
# server port, derived deterministically from the issue key so the port is
# stable across re-runs and unique per worktree.
#
# Environment contract (exported by the executor; the defaults below keep the
# script runnable by hand, which is how you will debug it):
#   JST_ISSUE_KEY  JST_WORKTREE_DIR  JST_BRANCH  JST_PARENT_BRANCH  JST_PROJECT_KEY
#
# Fail-soft: a non-zero exit is reported by the executor and the run
# continues — you cannot block the executor from here. Idempotent: every step
# is safe to run again in the same worktree.
set -euo pipefail

ISSUE_KEY="${JST_ISSUE_KEY:-$(git branch --show-current | sed -E 's#^[^/]+/([A-Z][A-Z0-9]+-[0-9]+).*#\1#')}"
WORKTREE_DIR="${JST_WORKTREE_DIR:-$(git rev-parse --show-toplevel)}"
BRANCH="${JST_BRANCH:-$(git branch --show-current)}"
PARENT_BRANCH="${JST_PARENT_BRANCH:-}"

cd "$WORKTREE_DIR"

# Deterministic per-worktree dev port: issue number -> a 1..100 offset above
# Vite's default 5173, so the main checkout (5173) is never shadowed. Modulo
# means two issues exactly 100 apart land on the same port; widen the range if
# the team ever runs that many worktrees at once.
ISSUE_NUM="${ISSUE_KEY##*-}"
case "$ISSUE_NUM" in
  '' | *[!0-9]*) ISSUE_NUM=0 ;;
esac
DEV_PORT=$(( 5174 + (ISSUE_NUM % 100) ))

echo "bootstrap: $ISSUE_KEY on $BRANCH (parent: ${PARENT_BRANCH:-none})"
echo "bootstrap: dev server port for this worktree -> $DEV_PORT"

# 1. Dependencies — each worktree has its own node_modules. `yarn install` is
#    already a no-op when the lockfile is satisfied, so no guard is needed.
if ! command -v yarn >/dev/null 2>&1; then
  echo "bootstrap: yarn not found on PATH — install it, then re-run." >&2
  exit 1
fi
yarn install --silent

# 2. Gitignored local files — a fresh worktree starts clean, and the work
#    needs two files git never carries over: .env.local (the site operator's
#    SITE_* values, CTA-182, docs/in-app-pages.md §5 — without them the build
#    has no legal pages) and server/engine-api/engines.local.json (the local
#    Stockfish binary paths; engines.example.json is the template — without
#    them yarn api:start has no engines to serve). Both are copied from the
#    main checkout — the parent of the common .git directory — and only when
#    the worktree lacks the file, so a worktree's own values always win.
#    Both being gitignored, the copies never dirty the worktree. A main
#    checkout missing a file skips it with a note; run by hand in the main
#    checkout itself, the worktree *is* the main checkout, so the file is
#    already there and there is nothing to copy. .env.local is copied before
#    step 3's port rewrite so the line written afterwards is the worktree's
#    own, and the existing keep-other-lines logic preserves the copied
#    SITE_* lines on re-runs.
MAIN_ROOT="$(dirname "$(git rev-parse --path-format=absolute --git-common-dir)")"

copy_from_main() {
  local rel="$1" src dst
  src="$MAIN_ROOT/$rel"
  dst="$WORKTREE_DIR/$rel"
  if [ -f "$dst" ]; then
    echo "bootstrap: $rel already present — kept"
  elif [ -f "$src" ]; then
    mkdir -p "$(dirname "$dst")"
    cp "$src" "$dst"
    echo "bootstrap: copied $rel from the main checkout"
  else
    echo "bootstrap: no $rel in the main checkout — skipped"
  fi
}

copy_from_main ".env.local"
copy_from_main "server/engine-api/engines.local.json"

# 3. Record the port. `*.local` is gitignored (root .gitignore), so this file
#    never dirties the worktree or reaches a commit. The port line is
#    rewritten each run so a changed scheme actually takes effect; every other
#    line is kept — the site operator's SITE_* values live here too (CTA-182,
#    docs/in-app-pages.md §5). Vite does not read a PORT env var itself — pass
#    --port explicitly (see the final line) or read VITE_DEV_PORT from your
#    own config.
ENV_FILE="$WORKTREE_DIR/.env.local"
KEPT=""
if [ -f "$ENV_FILE" ]; then
  KEPT="$(grep -v -e '^VITE_DEV_PORT=' -e '^# Generated by \.jst/bootstrap' "$ENV_FILE" || true)"
fi
{
  echo "# Generated by .jst/bootstrap.sh for $ISSUE_KEY — VITE_DEV_PORT is rewritten on each run, the other lines kept."
  echo "VITE_DEV_PORT=$DEV_PORT"
  if [ -n "$KEPT" ]; then printf '%s\n' "$KEPT"; fi
} > "$ENV_FILE.tmp"
mv "$ENV_FILE.tmp" "$ENV_FILE"

echo "bootstrap: ready — start this worktree's app with 'yarn dev --port $DEV_PORT'"
